from pydantic import BaseModel, Field
from app.ai.schema import RouterType


class EvaluationResult(BaseModel):
    router: RouterType = Field(
        ...,
        description="The route selected by Synapse's router.",
    )
    retrieved_context: str | None = Field(
        default=None,
        description="The retrieved context from the documents.",
    )
    web_context: str | None = Field(
        default=None,
        description="The web context from the web search.",
    )
    answer: str = Field(
        ...,
        description="The answer generated by Synapse.",
    )
